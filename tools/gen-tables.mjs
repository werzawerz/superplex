// Generates src/sim/tables.generated.ts from OpenSupaplex's animations.c (reverse-engineered
// data tables of the original: where each animation frame lives in MOVING.DAT, Murphy's
// animation descriptors). Usage: node tools/gen-tables.mjs [path/to/animations.c]
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(process.argv[2] ?? 'reference/open-supaplex/animations.c', 'utf8')
  .replace(/\r\n/g, '\n')
  .replace(/\/\/[^\n]*/g, '')
  .replace(/\/\*[\s\S]*?\*\//g, '');

/** Body text of `name ... = { ... };` */
function body(name) {
  const at = src.indexOf(name);
  if (at < 0) throw new Error(`missing ${name}`);
  const open = src.indexOf('{', src.indexOf('=', at));
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) return src.slice(open + 1, i);
  }
  throw new Error(`unterminated ${name}`);
}
const nums = (s) => [...s.matchAll(/-?0x[0-9a-fA-F]+|-?\d+/g)].map((m) => Number(m[0]));
const s16 = (v) => (v >= 0x8000 ? v - 0x10000 : v);
const points = (s) => {
  const n = nums(s);
  const out = [];
  for (let i = 0; i + 1 < n.length; i += 2) out.push([n[i], n[i + 1]]);
  return out;
};

const descriptors = [];
{
  const n = nums(body('kMurphyAnimationDescriptors'));
  for (let i = 0; i + 7 < n.length; i += 8) {
    const [offset, increment, width, height, animation, speedX, speedY] = n.slice(i, i + 7);
    descriptors.push({ offset: s16(offset), increment: s16(increment), width, height, animation, speedX: s16(speedX), speedY: s16(speedY) });
  }
}

// kMurphyAnimationFrameCoordinates: [{ { {x,y}... }, count }, ...]
const murphyFrames = [];
{
  const b = body('kMurphyAnimationFrameCoordinates');
  let depth = 0, start = -1;
  for (let i = 0; i < b.length; i++) {
    if (b[i] === '{') { if (depth === 0) start = i; depth++; }
    else if (b[i] === '}' && --depth === 0) {
      const entry = b.slice(start + 1, i);
      const close = entry.lastIndexOf('}');
      const pts = points(entry.slice(0, close));
      const count = nums(entry.slice(close + 1))[0];
      murphyFrames.push(pts.slice(0, count));
    }
  }
}

const pointTables = {
  bug: 'kBugFrameCoordinates',
  zonkSlideLeft: 'kZonkSlideLeftAnimationFrameCoordinates',
  zonkSlideRight: 'kZonkSlideRightAnimationFrameCoordinates',
  infotronSlideLeft: 'kInfotronSlideLeftAnimationFrameCoordinates',
  infotronSlideRight: 'kInfotronSlideRightAnimationFrameCoordinates',
  regularExplosion: 'kRegularExplosionAnimationFrameCoordinates',
  infotronExplosion: 'kInfotronExplosionAnimationFrameCoordinates',
  snikSnak: 'kSnikSnakAnimationFrameCoordinates',
  electron: 'kElectronAnimationFrameCoordinates',
};

let out = `// GENERATED by tools/gen-tables.mjs from OpenSupaplex's animations.c — do not edit.
// Frame positions in MOVING.DAT (x, y) and Murphy's animation descriptors from the original game.

export type Point = readonly [number, number];

export interface MurphyAnimation {
  /** Destination offset of the sprite: y = trunc(offset / 122), x = (offset % 122) * 8. */
  offset: number;
  increment: number;
  /** Width in units of 8 px. */
  width: number;
  height: number;
  /** Index into MURPHY_FRAMES. */
  animation: number;
  speedX: number;
  speedY: number;
}

export const MURPHY_ANIMATIONS: readonly MurphyAnimation[] = ${JSON.stringify(descriptors)};

export const MURPHY_FRAMES: readonly (readonly Point[])[] = ${JSON.stringify(murphyFrames)};
`;
for (const [k, v] of Object.entries(pointTables)) {
  out += `\nexport const ${k.replace(/[A-Z]/g, (c) => '_' + c).toUpperCase()}_FRAMES: readonly Point[] = ${JSON.stringify(points(body(v)))};\n`;
}
writeFileSync('src/sim/tables.generated.ts', out);
console.log('descriptors', descriptors.length, 'murphy animations', murphyFrames.length);
