// Generates src/ui/tables.generated.ts from OpenSupaplex's buttonBorders.c and supaplex.c:
// the original's menu button areas and the border lines it redraws to show a pressed button.
// Usage: node tools/gen-ui-tables.mjs [dir with buttonBorders.c and supaplex.c]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const dir = process.argv[2] ?? 'reference/open-supaplex';
const strip = (s) => s.replace(/\r\n/g, '\n').replace(/\/\/[^\n]*/g, '').replace(/\/\*[\s\S]*?\*\//g, '');
const borders = strip(readFileSync(`${dir}/buttonBorders.c`, 'utf8'));
const main = strip(readFileSync(`${dir}/supaplex.c`, 'utf8'));
const types = { Horizontal: 0, Vertical: 1, BottomLeftToTopRightDiagonal: 2, TopLeftToBottomRightDiagonal: 3 };

function body(src, name) {
  const at = src.indexOf(name);
  const open = src.indexOf('{', src.indexOf('=', at));
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) return src.slice(open + 1, i);
  }
  throw new Error(name);
}
function borderTable(name) {
  const b = body(borders, name);
  const out = [];
  let depth = 0, start = 0;
  for (let i = 0; i < b.length; i++) {
    if (b[i] === '{') { if (depth === 0) start = i; depth++; }
    else if (b[i] === '}' && --depth === 0) {
      const lines = [...b.slice(start, i).matchAll(/ButtonBorderLineType(\w+),\s*(\d+),\s*(\d+),\s*(\d+)/g)].map((m) => [types[m[1]], +m[2], +m[3], +m[4]]);
      out.push(lines);
    }
  }
  return out;
}
function buttons(name) {
  return [...body(main, name).matchAll(/\{\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\w+)/g)].map((m) => [+m[1], +m[2], +m[3], +m[4], m[5]]);
}
const mainButtons = buttons('kMainMenuButtonDescriptors[kNumberOfMainMenuButtons]');
const optionButtons = buttons('kOptionsMenuButtonDescriptors[kNumberOfOptionsMenuButtons]');
mkdirSync('src/ui', { recursive: true });
writeFileSync('src/ui/tables.generated.ts', `// GENERATED by tools/gen-ui-tables.mjs from OpenSupaplex — do not edit.
// Border lines: [type (0 horizontal →, 1 vertical ↑, 2 diagonal ↗, 3 diagonal ↘), x, y, length].
export type BorderLine = readonly [number, number, number, number];
/** Clickable areas: [x1, y1, x2, y2 (inclusive), original handler name]. */
export type ButtonArea = readonly [number, number, number, number, string];

export const MAIN_MENU_BORDERS: readonly (readonly BorderLine[])[] = ${JSON.stringify(borderTable('kMainMenuButtonBorders'))};
export const OPTIONS_MENU_BORDERS: readonly (readonly BorderLine[])[] = ${JSON.stringify(borderTable('kOptionsMenuBorders'))};
export const MAIN_MENU_BUTTONS: readonly ButtonArea[] = ${JSON.stringify(mainButtons)};
export const OPTIONS_MENU_BUTTONS: readonly ButtonArea[] = ${JSON.stringify(optionButtons)};
`);
console.log(borderTable('kMainMenuButtonBorders').length, borderTable('kOptionsMenuBorders').length, mainButtons.length, optionButtons.length);
